def _get_shell_cmd_invocation(cmd, shell):
    if "bat" in shell:
        return f"%{cmd}%"
    return cmd


def _get_load_cmds(spec, shell):
    load_script_file = spec_script.path_to_load_shell_script(spec, shell[2:])

    with open(load_script_file, "r", encoding="utf-8") as f:
        return f.read()


def _get_unload_cmds(spec, shell):
    unload_script_file = spec_script.path_to_unload_shell_script(spec, shell[2:])

    with open(unload_script_file, "r", encoding="utf-8") as f:
        return f.read()


@pytest.mark.parametrize("shell", (["--bat"] if sys.platform == "win32" else ["--sh"]))
def test_manpath_trailing_colon(
    shell, install_mockery, mock_fetch, mock_archive, mock_packages, working_env
):
    """Test that the commands generated by load add the MANPATH prefix inspections.
    Also test that Spack correctly preserves the default/existing manpath search path
    via a trailing colon"""

    install("--fake", "mpileaks")
    mpileaks_spec = spack.concretize.concretize_one("mpileaks")

    os.environ["MANPATH"] = "/usr/share/man" + os.pathsep + "/usr/local/share/man"

    load(shell, "mpileaks")
    load_cmds = _get_load_cmds(mpileaks_spec, shell)

    prepend_cmd = f"{_get_shell_cmd_invocation('_spack_env_prepend', shell)} MANPATH"
    manpath_prepends = [line for line in load_cmds.splitlines() if prepend_cmd in line]
    assert len(manpath_prepends) > 0, "Expected MANPATH prepends from loaded packages"

    append_cmd = f"{_get_shell_cmd_invocation('_spack_env_append', shell)} MANPATH"

    if "bat" in shell:
        expected_append = f'{append_cmd} "" ";"'
    else:
        expected_append = f"{append_cmd} '' :"

    trailing_colon_found = any(expected_append in line for line in load_cmds.splitlines())
    assert trailing_colon_found, (
        f"Expected trailing colon via: {expected_append}\n"
        f"This preserves system MANPATH entries.\n"
        f"Commands generated:\n{load_cmds}"
    )


def test_load_recursive(install_mockery, mock_fetch, mock_archive, mock_packages, working_env):
    def test_load_shell(shell):
        """Test that `spack load` applies prefix inspections of its required runtime deps in
        topo-order"""
        install("--fake", "mpileaks")
        mpileaks_spec = spack.concretize.concretize_one("mpileaks")

        # Ensure our reference variable is clean.
        os.environ["CMAKE_PREFIX_PATH"] = "/hello" + os.pathsep + "/world"

        load(shell, "mpileaks")

        load_cmds = _get_load_cmds(mpileaks_spec, shell)

        def extract_value(output, variable):
            value = []
            for line in output.splitlines():
                if not line:
                    continue

                info = line.split(" ")
                if info[1] == variable:
                    value.insert(0, info[2])
            return value

        # Map a prefix found in CMAKE_PREFIX_PATH back to a package name in mpileaks' DAG.
        prefix_to_pkg = lambda prefix: next(
            s.name for s in mpileaks_spec.traverse() if s.prefix == prefix
        )

        paths_shell = extract_value(load_cmds, "CMAKE_PREFIX_PATH")

        # All but the last two paths are added by spack load; lookup what packages they're from.
        pkgs = [prefix_to_pkg(p) for p in paths_shell]

        # Do we have all the runtime packages?
        assert set(pkgs) == {
            s.name for s in mpileaks_spec.traverse(deptype=("link", "run"), root=True)
        }

        # Finally, do we list them in topo order?
        for i, pkg in enumerate(pkgs):
            assert {s.name for s in mpileaks_spec[pkg].traverse(direction="parents")}.issubset(
                pkgs[: i + 1]
            )

        # Lastly, do we keep track that mpileaks was loaded?
        assert (
            extract_value(load_cmds, uenv.spack_loaded_hashes_var)[0] == mpileaks_spec.dag_hash()
        )
        return paths_shell

    if sys.platform == "win32":
        test_load_shell("--bat")
        test_load_shell("--pwsh")
    else:
        paths_sh = test_load_shell("--sh")
        paths_csh = test_load_shell("--csh")
        assert paths_sh == paths_csh


