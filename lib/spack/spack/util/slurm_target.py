"""Discover Slurm CPU architectures and compute their compatible Spack target.

The default inventory source is an explicit per-node ``archspec_<name>`` Slurm
feature. Slurm's CPU configuration is not itself an Archspec target. When
features are absent, users can explicitly opt into srun-based probes or provide
an independently checked JSON inventory. Missing nodes fail closed.
"""

import json
import os
import re
import subprocess
import tempfile
from pathlib import Path
from typing import Dict, List, Mapping, NamedTuple, Optional, Tuple

import spack.vendor.archspec.cpu as cpu


class SlurmTargetError(Exception):
    """The requested target compatibility guarantee cannot be established."""


_TARGET_RE = re.compile(r"^[A-Za-z0-9_]+$")
_FEATURE_PREFIX = "archspec_"
_MANAGED_MARKER = "# Generated by spack slurm-target; do not edit manually.\n"
_MANAGED_JSON_ID = "spack slurm-target"


class Node:
    def __init__(self, name: str, features: str, partitions=None, active_features: str = ""):
        self.name = name
        self.features = features
        self.active_features = active_features
        self.partitions = set(partitions or ())


class Resolution(NamedTuple):
    target: str
    strategy: str
    candidates: Tuple[str, ...]
    generic: str


def resolve(node_targets: Mapping[str, str], mode: str = "common") -> Resolution:
    """Select a DAG ancestor supported by every node, not the oldest CPU model.

    The unique maximal common ancestor is the most specific usable Archspec
    target. If multiple incomparable maxima exist, use the unique maximal
    *generic* common ancestor instead of arbitrarily choosing a CPU model.
    """
    if mode not in ("common", "generic"):
        raise SlurmTargetError(f"unknown target mode: {mode}")
    if not node_targets:
        raise SlurmTargetError("no compute nodes selected")

    targets = []
    for node, name in sorted(node_targets.items()):
        try:
            targets.append(cpu.TARGETS[name])
        except KeyError as e:
            raise SlurmTargetError(
                f"{node}: unknown Archspec target {name!r}; use spack arch --known-targets"
            ) from e

    families = {str(t.family) for t in targets}
    if len(families) != 1:
        raise SlurmTargetError(
            "nodes have incompatible architecture families: " + ", ".join(sorted(families))
        )

    common = set.intersection(*({str(t)} | {str(p) for p in t.ancestors} for t in targets))
    if not common:
        raise SlurmTargetError("no common Archspec ancestor")

    def maximal(names):
        return tuple(
            sorted(
                name
                for name in names
                if not any(
                    name != other and cpu.TARGETS[name] < cpu.TARGETS[other] for other in names
                )
            )
        )

    generics = {name for name in common if cpu.TARGETS[name].vendor == "generic"}
    generic_maximal = maximal(generics)
    if len(generic_maximal) != 1:
        raise SlurmTargetError("generic targets are ambiguous: " + ", ".join(generic_maximal))
    generic = generic_maximal[0]
    if mode == "generic":
        return Resolution(generic, "generic", (generic,), generic)

    candidates = maximal(common)
    if len(candidates) == 1:
        return Resolution(candidates[0], "common-ancestor", candidates, generic)
    return Resolution(generic, "ambiguous-generic-fallback", candidates, generic)


def run_command(argv: List[str], timeout: int = 25) -> str:
    """Run a fixed argv list; never execute Slurm output through a shell."""
    try:
        p = subprocess.run(
            argv,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=True,
            timeout=timeout,
        )
        return p.stdout
    except FileNotFoundError as e:
        raise SlurmTargetError(f"required executable not found: {argv[0]}") from e
    except subprocess.TimeoutExpired as e:
        raise SlurmTargetError(f"timed out running: {argv[0]}") from e
    except subprocess.CalledProcessError as e:
        raise SlurmTargetError(
            f"{argv[0]} failed (exit {e.returncode}): {(e.stderr or '').strip()[-500:]}"
        ) from e


def slurm_nodes(partition: Optional[str] = None, *, runner=run_command) -> Dict[str, Node]:
    """Enumerate *all* visible nodes, including drained/down nodes.

    ``-N`` expands node rows; duplicates across partitions are deduplicated.
    The selected partition must be treated as a workload policy, not an
    arbitrary snapshot of currently available nodes.
    """
    # Slurm rejects --all (-a) together with --partition (-p).
    command = ["sinfo", "-N", "-h", "-o", "%N|%f|%b|%P"]
    if partition:
        command.extend(["-p", partition])
    else:
        command.append("-a")
    result: Dict[str, Node] = {}
    for line in runner(command, timeout=25).splitlines():
        if not line.strip():
            continue
        fields = [s.strip() for s in line.split("|")]
        if len(fields) != 4:
            raise SlurmTargetError(f"unexpected sinfo row: {line!r}")
        name, features, active_features, partitions = fields
        if not re.fullmatch(r"[A-Za-z0-9_.-]+", name) or not partitions:
            raise SlurmTargetError(f"invalid sinfo node or partition: {line!r}")
        part = partitions.rstrip("*")
        if name in result:
            if (
                result[name].features != features
                or result[name].active_features != active_features
            ):
                raise SlurmTargetError(f"inconsistent features for Slurm node {name}")
            result[name].partitions.add(part)
        else:
            result[name] = Node(
                name=name, features=features, active_features=active_features, partitions={part}
            )
    if not result:
        raise SlurmTargetError("Slurm did not return any nodes")
    return result


def _feature_archspec_target(features: str, node_name: str, source: str) -> Optional[str]:
    """Read exactly one target from a Slurm feature string, when present."""
    tags = [
        s[len(_FEATURE_PREFIX) :] for s in features.split(",") if s.startswith(_FEATURE_PREFIX)
    ]
    if not tags:
        return None
    if len(tags) != 1 or not _TARGET_RE.fullmatch(tags[0]):
        raise SlurmTargetError(
            f"{node_name}: expected exactly one archspec_<target> in {source}; got {features!r}"
        )
    return tags[0]


def feature_target(node: Node) -> Optional[str]:
    """Validate AvailableFeatures against ActiveFeatures when active metadata exists."""
    available = _feature_archspec_target(node.features, node.name, "AvailableFeatures")
    active = _feature_archspec_target(node.active_features, node.name, "ActiveFeatures")
    if active and active != available:
        raise SlurmTargetError(
            f"{node.name}: ActiveFeatures archspec target {active!r} differs from "
            f"AvailableFeatures {available!r}; CPU target cannot be trusted"
        )
    return available


def read_inventory(path: str) -> Dict[str, str]:
    try:
        data = json.loads(Path(path).expanduser().read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise SlurmTargetError(f"cannot read JSON inventory {path}: {e}") from e
    if (
        not isinstance(data, dict)
        or not data
        or any(
            not isinstance(k, str)
            or not k
            or not isinstance(v, str)
            or not _TARGET_RE.fullmatch(v)
            for k, v in data.items()
        )
    ):
        raise SlurmTargetError("inventory must be a nonempty JSON object {node: archspec_target}")
    return data


def probe_target(
    node: Node,
    *,
    partition: Optional[str],
    account: Optional[str],
    qos: Optional[str],
    spack_executable: str,
    runner=run_command,
) -> str:
    """Explicitly run one Slurm job on a selected compute node (never by default)."""
    candidates = sorted(node.partitions)
    requested = set(partition.split(",")) if partition else set(candidates)
    eligible = sorted(set(candidates).intersection(requested))
    if not eligible:
        raise SlurmTargetError(f"{node.name}: not in requested Slurm partitions")
    command = [
        "srun",
        "--nodes=1",
        "--ntasks=1",
        f"--nodelist={node.name}",
        f"--partition={eligible[0]}",
        "--immediate=10",
        "--time=00:02:00",
    ]
    if account:
        command.append(f"--account={account}")
    if qos:
        command.append(f"--qos={qos}")
    command += [spack_executable, "arch", "--target"]
    lines = [s.strip() for s in runner(command, timeout=90).splitlines() if s.strip()]
    if len(lines) != 1 or not _TARGET_RE.fullmatch(lines[0]):
        raise SlurmTargetError(f"{node.name}: invalid target reported by compute node")
    return lines[0]


def discover(
    *,
    partition: Optional[str] = None,
    source: str = "features",
    inventory: Optional[str] = None,
    account: Optional[str] = None,
    qos: Optional[str] = None,
    max_probes: int = 32,
    spack_executable: Optional[str] = None,
    runner=run_command,
) -> Dict[str, str]:
    """Discover exact per-node targets from Slurm; fail if a node is unknown.

    ``file`` is an offline test input and is NOT independently checked against
    live Slurm membership. Other modes always enumerate live Slurm nodes.
    """
    if source not in ("features", "auto", "probe", "file"):
        raise SlurmTargetError(f"unsupported inventory source: {source}")
    if max_probes < 0:
        raise SlurmTargetError("max_probes must not be negative")
    if source == "file":
        if not inventory:
            raise SlurmTargetError("--source file requires --inventory PATH")
        if partition:
            raise SlurmTargetError(
                "--partition cannot filter --source file; provide an inventory for "
                "the intended node set instead"
            )
        return read_inventory(inventory)
    nodes = slurm_nodes(partition, runner=runner)
    detected = {}
    if source != "probe":
        for node in nodes.values():
            target = feature_target(node)
            if target:
                detected[node.name] = target
    missing = sorted(set(nodes) - set(detected))
    if missing and source == "features":
        raise SlurmTargetError(
            f"{len(missing)} nodes lack archspec_<target> Slurm features "
            f"(e.g. {', '.join(missing[:5])}); select --source auto to probe explicitly"
        )
    if len(missing) > max_probes:
        raise SlurmTargetError(
            f"probing {len(missing)} nodes would exceed --max-probes={max_probes}; "
            "publish Slurm features or provide a verified inventory"
        )
    if not spack_executable:
        if missing:
            raise SlurmTargetError("compute-node probing requires a Spack executable")
        return detected
    for name in missing:
        detected[name] = probe_target(
            nodes[name],
            partition=partition,
            account=account,
            qos=qos,
            spack_executable=spack_executable,
            runner=runner,
        )
    return detected


def write_scope(
    directory: str,
    resolution: Resolution,
    nodes: Mapping[str, str],
    *,
    partition: Optional[str],
    source: str,
    mode: str,
) -> Path:
    """Write an isolated, strict Spack -C config scope with recorded inventory.

    Do not touch ~/.spack/packages.yaml or site configuration. Existing
    unmanaged files are never overwritten.
    """
    target = resolution.target
    if not _TARGET_RE.fullmatch(target):
        raise SlurmTargetError(f"invalid target name for configuration: {target!r}")
    path = Path(directory).expanduser().resolve()
    path.mkdir(parents=True, exist_ok=True)
    files = {
        "packages.yaml": (
            _MANAGED_MARKER + "packages:\n  all:\n"
            f"    target: [{target}]\n    require:\n    - 'target={target}'\n"
        ),
        "concretizer.yaml": (
            _MANAGED_MARKER + "concretizer:\n  targets:\n"
            "    granularity: microarchitectures\n    host_compatible: false\n"
        ),
        "slurm-target.json": json.dumps(
            {
                "generated_by": _MANAGED_JSON_ID,
                "source": source,
                "mode": mode,
                "partition": partition,
                "selected_target": target,
                "strategy": resolution.strategy,
                "generic_target": resolution.generic,
                "node_targets": dict(sorted(nodes.items())),
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
    }
    for name in files:
        p = path / name
        if p.exists():
            if name == "slurm-target.json":
                try:
                    owned = json.loads(p.read_text(encoding="utf-8"))
                except (OSError, ValueError) as e:
                    raise SlurmTargetError(f"unmanaged or malformed file: {p}") from e
                if not isinstance(owned, dict) or owned.get("generated_by") != _MANAGED_JSON_ID:
                    raise SlurmTargetError(f"unmanaged file: {p}")
            elif not p.read_text(encoding="utf-8").startswith(_MANAGED_MARKER):
                raise SlurmTargetError(f"refusing to overwrite unmanaged config: {p}")
    for name, contents in files.items():
        fd, tmp = tempfile.mkstemp(dir=path, prefix=".slurm-target-", text=True)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                f.write(contents)
                f.flush()
                os.fsync(f.fileno())
            os.replace(tmp, path / name)
        finally:
            if os.path.exists(tmp):
                os.unlink(tmp)
    return path
